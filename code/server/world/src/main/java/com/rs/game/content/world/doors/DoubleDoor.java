package com.rs.game.content.world.doors;

public class DoubleDoor {

	private final int first;
	private final int second;

	public DoubleDoor(int first, int second) {
		this.first = first;
		this.second = second;
	}

	public int getFirst() {
		return first;
	}

	public int getSecond() {
		return second;
	}
}
