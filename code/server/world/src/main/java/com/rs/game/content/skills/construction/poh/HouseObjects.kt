    companion object {
        fun getDynamicObjectId(player: Player?, objectType: HouseObjects): Int {
            return when (objectType) {
                OAK_DECORATION -> HouseHeraldry.OAK_WALL_DECORATION_IDS[HouseHeraldry.getCurrentCrest(player).ordinal]
                TEAK_DECORATION -> HouseHeraldry.TEAK_WALL_DECORATION_IDS[HouseHeraldry.getCurrentCrest(player).ordinal]
                GILDED_DECORATION -> HouseHeraldry.MAHOGANY_WALL_DECORATION_IDS[HouseHeraldry.getCurrentCrest(player).ordinal]
                ROUND_SHIELD -> HouseHeraldry.ROUND_SHIELD_IDS[HouseHeraldry.getCurrentCrest(player).ordinal]
                SQUARE_SHIELD -> HouseHeraldry.SQUARE_SHIELD_IDS[HouseHeraldry.getCurrentCrest(player).ordinal]
                KITE_SHIELD -> HouseHeraldry.KITE_SHIELD_IDS[HouseHeraldry.getCurrentCrest(player).ordinal]
                else -> objectType.objectIds[0]
            }
        }
    }

    constructor(itemId: Int, objectIds: IntArray, level: Int, xp: Int, vararg reqs: Item?) :
            this(itemId, objectIds, level, xp.toDouble(), reqs.filterNotNull()) // Convert xp to Double and filter null reqs

    constructor(itemId: Int, objectId: Int, level: Int, xp: Int , vararg reqs: Item?) :
            this(itemId, intArrayOf(objectId), level, xp.toDouble(), reqs.filterNotNull()) // Single objectId turned into an array

    constructor(itemId: Int, level: Int, xp: Int, vararg reqs: Item?) :
            this(itemId, intArrayOf(0), level, xp.toDouble(), reqs.filterNotNull()) // Default objectIds to [0]

    fun getId(): Int {
        return objectIds[0]
    }

    fun getIds(): IntArray {
        return objectIds
    }

    fun getRequirements(player: Player): Array<Item?> {
        val items = arrayOfNulls<Item>(reqs.size)
        for (i in reqs.indices) {
            if (reqs[i].id == HouseConstants.NAILS) {
                for (nailId in HouseConstants.NAIL_IDS) {
                    if (player.inventory.containsItem(nailId)) {
                        items[i] = Item(nailId, reqs[i].amount)
                        break
                    }
                }
            } else {
                items[i] = reqs[i]
            }
        }
        return items
    }

    fun getXP(): Double {
        return xp
    }
